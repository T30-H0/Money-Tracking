export function translate(
  locale: Locale,
  key: MessageKey,
  params?: TranslationParams,
) {
  const template = messages[locale][key] ?? messages.en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(params[name] ?? `{${name}}`),
  );
}
